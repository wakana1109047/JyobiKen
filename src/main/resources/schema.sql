CREATE TABLE IF NOT EXISTS roles (
    code VARCHAR(32) PRIMARY KEY,
    name VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    user_type VARCHAR(32) NOT NULL DEFAULT 'GENERAL_STUDENT'
        CHECK (user_type IN ('GENERAL_STUDENT', 'RESEARCH_STUDENT', 'ALUMNI', 'ADMIN')),
    account_status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE'
        CHECK (account_status IN ('ACTIVE', 'SUSPENDED', 'EXPIRED')),
    expires_at DATE,
    recovery_email VARCHAR(255),
    department VARCHAR(50),
    CONSTRAINT fk_app_user_user_type FOREIGN KEY (user_type) REFERENCES roles(code)
);

ALTER TABLE app_user
    ADD COLUMN IF NOT EXISTS user_type VARCHAR(32) NOT NULL DEFAULT 'GENERAL_STUDENT';
ALTER TABLE app_user
    ADD COLUMN IF NOT EXISTS account_status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE';
ALTER TABLE app_user
    ADD COLUMN IF NOT EXISTS expires_at DATE;
ALTER TABLE app_user
    ADD COLUMN IF NOT EXISTS recovery_email VARCHAR(255);
ALTER TABLE app_user
    ADD COLUMN IF NOT EXISTS department VARCHAR(50);

CREATE TABLE IF NOT EXISTS research_group (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    description TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'active',
    created_by BIGINT REFERENCES app_user(id),
    is_recruiting BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE research_group
    ADD COLUMN IF NOT EXISTS description TEXT;
ALTER TABLE research_group
    ADD COLUMN IF NOT EXISTS status VARCHAR(20) NOT NULL DEFAULT 'active';
ALTER TABLE research_group
    ADD COLUMN IF NOT EXISTS created_by BIGINT REFERENCES app_user(id);
ALTER TABLE research_group
    ADD COLUMN IF NOT EXISTS is_recruiting BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE research_group
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP;

CREATE TABLE IF NOT EXISTS group_membership (
    group_id BIGINT NOT NULL REFERENCES research_group(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    group_role VARCHAR(16) NOT NULL DEFAULT 'MEMBER'
        CHECK (group_role IN ('LEADER', 'MEMBER', 'ADMIN')),
    joined_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (group_id, user_id)
);

ALTER TABLE group_membership
    DROP CONSTRAINT IF EXISTS group_membership_group_role_check;
ALTER TABLE group_membership
    ADD CONSTRAINT group_membership_group_role_check
        CHECK (group_role IN ('LEADER', 'MEMBER', 'ADMIN'));

CREATE TABLE IF NOT EXISTS admin_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_email VARCHAR(255) NOT NULL,
    action VARCHAR(64) NOT NULL,
    target_type VARCHAR(64) NOT NULL,
    target_id BIGINT,
    details VARCHAR(2000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL UNIQUE REFERENCES research_group(id),
    title VARCHAR(255) NOT NULL,
    summary TEXT,
    academic_year INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'planning',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id),
    created_by_user_id BIGINT NOT NULL REFERENCES app_user(id),
    content TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'draft',
    version INTEGER NOT NULL DEFAULT 0,
    published_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES posts(id),
    created_by_user_id BIGINT NOT NULL REFERENCES app_user(id),
    parent_comment_id BIGINT REFERENCES comments(id),
    content VARCHAR(500) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'published',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS reaction_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(50) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS post_reactions (
    post_id BIGINT NOT NULL REFERENCES posts(id),
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    reaction_type_id BIGINT NOT NULL REFERENCES reaction_types(id),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (post_id, user_id, reaction_type_id)
);

CREATE TABLE IF NOT EXISTS project_reactions (
    project_id BIGINT NOT NULL REFERENCES projects(id),
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    reaction_type_id BIGINT NOT NULL REFERENCES reaction_types(id),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (project_id, user_id, reaction_type_id)
);

CREATE TABLE IF NOT EXISTS tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(10) NOT NULL UNIQUE,
    tag_type VARCHAR(20) NOT NULL DEFAULT 'hashtag',
    created_by_user_id BIGINT NOT NULL REFERENCES app_user(id),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS project_tags (
    project_id BIGINT NOT NULL REFERENCES projects(id),
    tag_id BIGINT NOT NULL REFERENCES tags(id),
    PRIMARY KEY (project_id, tag_id)
);

CREATE TABLE IF NOT EXISTS post_tags (
    post_id BIGINT NOT NULL REFERENCES posts(id),
    tag_id BIGINT NOT NULL REFERENCES tags(id),
    PRIMARY KEY (post_id, tag_id)
);

CREATE TABLE IF NOT EXISTS files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id),
    post_id BIGINT REFERENCES posts(id),
    uploaded_by_user_id BIGINT NOT NULL REFERENCES app_user(id),
    file_purpose VARCHAR(20) NOT NULL DEFAULT 'post',
    original_name VARCHAR(50) NOT NULL,
    sizes_bytes BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS bookmarks (
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    project_id BIGINT NOT NULL REFERENCES projects(id),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, project_id)
);

CREATE TABLE IF NOT EXISTS view_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id),
    viewer_user_id BIGINT NOT NULL REFERENCES app_user(id),
    viewed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
